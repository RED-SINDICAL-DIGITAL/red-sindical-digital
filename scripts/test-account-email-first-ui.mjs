import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const ui=await readFile(new URL('../uadav-profile-email.js',import.meta.url),'utf8');
const page=await readFile(new URL('../usuario.html',import.meta.url),'utf8');
const email=await readFile(new URL('../entrar-correo.html',import.meta.url),'utf8');
assert.match(page,/id="profileTasks"/,'Mi Perfil must retain its familiar activity section');
assert.match(page,/id="profileSettings"/,'Legacy account recovery must remain present');
assert.match(ui,/tasks\.before\(panel\)/,'Email first action must be visible before daily tasks');
assert.match(ui,/panel\.hidden=true/,'Do not reveal login before backend status is known');
assert.match(ui,/status\?\.installed/,'Email-first action requires installed backend');
assert.match(ui,/status\.enabled===true/,'Email-first action requires enabled backend');
assert.match(ui,/href='\/entrar-correo\.html'/,'Email-first must navigate to existing login');
assert.match(ui,/min-height:44px/,'Primary action must be accessible by touch');
assert.match(ui,/Sin contraseñas ni códigos que copiar/,'Plain language must replace technical language');
assert.doesNotMatch(ui,/localStorage\.(?:setItem|removeItem)|sessionStorage\.(?:setItem|removeItem)|\.disconnect\(|\.create\(/,'Presentation must not mutate or replace accounts');
assert.match(email,/id="confirmEmail"/,'One-time link continues to require explicit confirmation');
assert.match(email,/id="emailConsent"/,'Email opt-in remains explicit');
assert.match(page,/id="showAccountCode"/,'Legacy pairing must remain during migration');
console.log('PASS: email-first UI gated to staging, accessible and non-destructive; legacy account flows preserved.');
